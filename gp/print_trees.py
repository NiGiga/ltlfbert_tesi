"""
Utility to print formulas from GP-generated datasets along with their genetic syntax trees.

Usage examples:
  python gp/print_trees.py
  python gp/print_trees.py -n 3
  python gp/print_trees.py -f data_gp/train.json -n 5 --random
  python gp/print_trees.py --formula "(F(p1) U F((X[!](G(p1)) & p3)))"
"""

import argparse
import json
import os
import random
import re
import sys


def parse_ltl_tree(s):
    """
    Parses a formula string generated by GP into a nested AST tuple:
      - Terminals: 'p0', 'p1', etc.
      - Unary ops: (op, child)
      - Binary ops: (op, left, right)
    """
    s = s.strip()
    if re.fullmatch(r"p\d+", s):
        return s
    if s.startswith("X[!](") and s.endswith(")"):
        return ("X", parse_ltl_tree(s[5:-1]))
    if s.startswith("F(") and s.endswith(")"):
        return ("F", parse_ltl_tree(s[2:-1]))
    if s.startswith("G(") and s.endswith(")"):
        return ("G", parse_ltl_tree(s[2:-1]))
    if s.startswith("!(") and s.endswith(")"):
        return ("NOT", parse_ltl_tree(s[2:-1]))
    if s.startswith("(") and s.endswith(")"):
        depth = 0
        inner = s[1:-1]
        for i, ch in enumerate(inner):
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif depth == 0:
                for op, name in [(" -> ", "IMPL"), (" & ", "AND"), (" | ", "OR"), (" U ", "U")]:
                    if inner[i:].startswith(op):
                        left = inner[:i]
                        right = inner[i + len(op):]
                        return (name, parse_ltl_tree(left), parse_ltl_tree(right))

    # Fallback to Spot parser if available
    try:
        import spot
        return _spot_to_tree(spot.formula(s))
    except Exception:
        raise ValueError(f"Unable to parse formula: {s}")


def _spot_to_tree(f):
    if f.size() == 0 or f.is_leaf():
        return f.to_str()
    op = f.kindstr()
    children = [_spot_to_tree(c) for c in f]
    return (op, *children)


def tree_stats(node):
    """Returns (node_count, depth)."""
    if isinstance(node, str):
        return 1, 1
    op, *children = node
    c_stats = [tree_stats(c) for c in children]
    size = 1 + sum(s for s, _ in c_stats)
    depth = 1 + max(d for _, d in c_stats)
    return size, depth


def to_deap_prefix(node):
    """Formats the tree in DEAP prefix notation (e.g. AND(p0, NOT(p1)))."""
    if isinstance(node, str):
        return node
    op, *children = node
    return f"{op}({', '.join(to_deap_prefix(c) for c in children)})"


def format_tree_ascii(node, prefix="", is_tail=True, is_root=True):
    """Formats the tree as an ASCII / Unicode hierarchy."""
    if is_root:
        if isinstance(node, str):
            return [node]
        lines = [node[0]]
        children = node[1:]
        for i, child in enumerate(children):
            lines.extend(format_tree_ascii(child, "", is_tail=(i == len(children) - 1), is_root=False))
        return lines

    marker = "└── " if is_tail else "├── "
    child_prefix = prefix + ("    " if is_tail else "│   ")
    if isinstance(node, str):
        return [prefix + marker + node]

    lines = [prefix + marker + node[0]]
    children = node[1:]
    for i, child in enumerate(children):
        lines.extend(format_tree_ascii(child, child_prefix, is_tail=(i == len(children) - 1), is_root=False))
    return lines


def to_dot(node):
    """Generates Graphviz DOT representation of the tree."""
    nodes = []
    edges = []

    def walk(n):
        node_id = len(nodes)
        if isinstance(n, str):
            nodes.append((node_id, n))
            return node_id
        op, *children = n
        nodes.append((node_id, op))
        for c in children:
            cid = walk(c)
            edges.append((node_id, cid))
        return node_id

    walk(node)
    lines = ["digraph GeneticTree {", "  node [fontname=\"Courier\", shape=box, style=rounded];"]
    for nid, label in nodes:
        lines.append(f'  {nid} [label="{label}"];')
    for u, v in edges:
        lines.append(f"  {u} -> {v};")
    lines.append("}")
    return "\n".join(lines)


def load_formulas(path):
    """Loads formula strings from formulas.json or split files (train.json, etc.)."""
    with open(path, "r") as fp:
        data = json.load(fp)

    formulas = []
    if isinstance(data, list):
        for item in data:
            if isinstance(item, list) or isinstance(item, tuple):
                formulas.append(item[0])
            elif isinstance(item, dict) and "formula" in item:
                formulas.append(item["formula"])
            elif isinstance(item, str):
                formulas.append(item)
    return formulas


def print_single_formula(f_str, idx=None, total=None, show_dot=False):
    header = f"Formula [{idx}/{total}]" if idx is not None and total is not None else "Formula"
    tree = parse_ltl_tree(f_str)
    size, depth = tree_stats(tree)
    prefix_str = to_deap_prefix(tree)
    tree_lines = format_tree_ascii(tree)

    print("=" * 70)
    print(f"{header}: {f_str}")
    print(f"DEAP prefix:  {prefix_str}")
    print(f"Size: {size} nodes | Depth: {depth}")
    print("-" * 70)
    print("Genetic Tree:")
    print("\n".join(tree_lines))
    if show_dot:
        print("-" * 70)
        print("Graphviz DOT:")
        print(to_dot(tree))
    print()


def main():
    parser = argparse.ArgumentParser(description="Print formulas with genetic trees from GP dataset.")
    parser.add_argument(
        "-f", "--file",
        type=str,
        default="data_gp/formulas.json",
        help="Path to dataset JSON file (formulas.json, train.json, ood.json, etc.)"
    )
    parser.add_argument(
        "-n", "--num",
        type=int,
        default=5,
        help="Number of formulas to print (default: 5)"
    )
    parser.add_argument(
        "--formula",
        type=str,
        default=None,
        help="Print a specific formula string instead of reading a file"
    )
    parser.add_argument(
        "-r", "--random",
        action="store_true",
        help="Select formulas randomly instead of taking the first N"
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for selection"
    )
    parser.add_argument(
        "--dot",
        action="store_true",
        help="Also output Graphviz DOT representation for each tree"
    )

    args = parser.parse_args()

    if args.formula:
        print_single_formula(args.formula, show_dot=args.dot)
        return

    if not os.path.exists(args.file):
        print(f"Error: File '{args.file}' not found.", file=sys.stderr)
        sys.exit(1)

    formulas = load_formulas(args.file)
    if not formulas:
        print(f"No formulas found in '{args.file}'.", file=sys.stderr)
        sys.exit(1)

    # Remove duplicates preserving order
    seen = set()
    unique_formulas = []
    for f in formulas:
        if f not in seen:
            seen.add(f)
            unique_formulas.append(f)

    if args.random:
        if args.seed is not None:
            random.seed(args.seed)
        selected = random.sample(unique_formulas, min(args.num, len(unique_formulas)))
    else:
        selected = unique_formulas[:args.num]

    for i, f_str in enumerate(selected, 1):
        print_single_formula(f_str, idx=i, total=len(selected), show_dot=args.dot)


if __name__ == "__main__":
    main()
